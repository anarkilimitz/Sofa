export function initConditionsPopup(lenis) {
	const overlay = document.getElementById('conditionsPopupOverlay');
	const popup = document.getElementById('conditionsPopup');
	const closeBtn = document.getElementById('conditionsPopupClose');
	const inner = popup ? popup.querySelector('.conditions-popup__inner') : null;
	const img = document.getElementById('conditionsPopupImg');
	const title = document.getElementById('conditionsPopupTitle');
	const text = document.getElementById('conditionsPopupText');
	const slides = document.querySelectorAll('.conditions__column');
	// функция показа скелетона
	function showPopupSkeleton() {
		const imgWrap = popup.querySelector('.conditions-popup__image-wrap');
		if (!imgWrap) return;

		img.style.display = 'none';
		imgWrap.classList.add('is-loading');

		if (imgWrap.querySelector('.skeleton')) return;

		const skeletonEl = document.createElement('div');
		skeletonEl.className = 'skeleton';
		skeletonEl.innerHTML = `
		<div class="skeleton__header">
			<div class="skeleton__circle"></div>
			<div class="skeleton__mini">Временно битая ссылка</div>
		</div>
		<div class="skeleton__block">ТУТ БУДЕТ КРАСИВЫЙ СКЕЛЕТОН</div>
		<div class="skeleton__block"></div>
		<div class="skeleton__block"></div>
	`;

		imgWrap.appendChild(skeletonEl);
	}

	if (!overlay || !popup || !slides.length) return;

	let tl = null;
	let mouseDownPos = null;
	let isOpen = false;
	let currentY = 0; // текущий сдвиг попапа в px
	let startY = 0;
	let startTouchY = 0;

	// ——— хелперы скролла попапа ———
	function clampY(y) {
		const TOP_GAP = -500; // сколько должно оставаться сверху

		const popupH = popup.offsetHeight;

		const minY = Math.min(startY, window.innerHeight - popupH - TOP_GAP);

		const maxY = startY;

		return Math.max(minY, Math.min(maxY, y));
	}

	function onWheel(e) {
		if (!isOpen) return;
		e.preventDefault();

		if (popup.contains(e.target) || e.target === popup) {
			currentY = clampY(currentY - e.deltaY);
			// console.log({
			// 	currentY,
			// 	startY,
			// 	popupH: popup.offsetHeight,
			// 	innerH: inner.scrollHeight,
			// 	windowH: window.innerHeight,
			// });
			gsap.set(popup, { y: currentY });
		}
	}

	function onTouchStart(e) {
		if (!isOpen) return;
		startTouchY = e.touches[0].clientY;
	}

	function onTouchMove(e) {
		 if (!isOpen) return;

			const delta = e.touches[0].clientY - startTouchY;
			startTouchY = e.touches[0].clientY;

			// пока попап еще двигается
			if (currentY > clampY(-99999)) {
				e.preventDefault();

				currentY = clampY(currentY + delta);
				gsap.set(popup, { y: currentY });

				return;
			}

		if (popup.contains(e.target) || e.target === popup) {
			const delta = e.touches[0].clientY - startTouchY;
			startTouchY = e.touches[0].clientY;
			currentY = clampY(currentY + delta);
			gsap.set(popup, { y: currentY });
		}
	}

	// слушатели вешаем один раз
	document.addEventListener('wheel', onWheel, { passive: false });
	document.addEventListener('touchstart', onTouchStart, { passive: false });
	document.addEventListener('touchmove', onTouchMove, { passive: false });

	// ——— open / close ———
	function open(slide) {
		const slideImg = slide.querySelector('.conditions__img img');
		const slideTitle = slide.querySelector('.conditions__column-title');
		// очистка предыдущего скелетона
		const imgWrap = popup.querySelector('.conditions-popup__image-wrap');

		img.style.display = '';
		imgWrap.classList.remove('is-loading');

		const oldSkeleton = imgWrap.querySelector('.skeleton');
		if (oldSkeleton) oldSkeleton.remove();

		let animated = false;
		// анимация попапа
		function animatePopup() {
			if (animated) return;
			animated = true;
			if (tl) tl.kill();

			requestAnimationFrame(() => {
				startY = Math.max(0, popup.offsetHeight - window.innerHeight * 0.7);
				currentY = startY;

				gsap.set(popup, {
					y: popup.offsetHeight,
					opacity: 0,
				});

				popup.style.pointerEvents = 'auto';

				tl = gsap.to(popup, {
					y: startY,
					opacity: 1,
					duration: 0.45,
					ease: 'power3.out',
				});
			});
		}

		img.onload = null;
		img.onerror = null;

		img.onload = () => {
			img.style.display = '';
			imgWrap.classList.remove('is-loading');
			imgWrap.querySelector('.skeleton')?.remove();

			animatePopup();
		};

		img.onerror = () => {
			showPopupSkeleton();
			animatePopup();
		};

		img.src = slideImg ? slideImg.src : '';
		img.alt = slideImg ? slideImg.alt : '';

		if (img.complete) {
			if (img.naturalWidth > 0) {
				animatePopup();
			} else {
				showPopupSkeleton();
				animatePopup();
			}
		}

		title.textContent = slideTitle ? slideTitle.textContent : '';

		const data = popupContent[title.textContent];
		text.innerHTML = data?.text || '';

		overlay.classList.add('active');
		document.documentElement.classList.add('search-open');
		document.body.classList.add('search-open');
		document.body.style.overflow = 'hidden'; // доп. блокировка

		popup.setAttribute('data-lenis-prevent', '');

		if (lenis) lenis.stop();

		isOpen = true;
	}
	// закрытие попапа
	function close() {
		if (!isOpen) return;
		if (tl) tl.kill();

		isOpen = false;
		popup.style.pointerEvents = 'none';

		tl = gsap.to(popup, {
			y: popup.offsetHeight,
			opacity: 0,
			duration: 0.35,
			ease: 'power2.in',
			onComplete() {
				overlay.classList.remove('active');
				document.documentElement.classList.remove('search-open');
				document.body.classList.remove('search-open');
				document.body.style.overflow = '';

				popup.removeAttribute('data-lenis-prevent');
				currentY = 0;

				if (lenis) lenis.start();
			},
		});
	}

	// ——— клики по слайдам ———
	slides.forEach((slide) => {
		slide.addEventListener('mousedown', (e) => {
			mouseDownPos = { x: e.clientX, y: e.clientY };
		});

		slide.addEventListener('click', (e) => {
			if (mouseDownPos) {
				const dx = e.clientX - mouseDownPos.x;
				const dy = e.clientY - mouseDownPos.y;
				const dist = Math.sqrt(dx * dx + dy * dy);
				mouseDownPos = null;
				if (dist > 5) return;
			}
			open(slide);
		});
	});

	if (closeBtn) {
		closeBtn.addEventListener('click', (e) => {
			e.stopPropagation();
			close();
		});
	}

	if (inner) {
		inner.addEventListener('click', (e) => e.stopPropagation());
	}

	popup.addEventListener('click', close);
	overlay.addEventListener('click', close);
}
